import assert from 'node:assert/strict'

export async function checkTeamEditor(page, baseURL, teamId, screenshotDir) {
  const api = page.context().request
  const route = `${baseURL}/api/members/teams/${teamId}`
  const headers = { 'X-Caesar-Client': 'members' }
  const read = async () => (await (await api.get(`${baseURL}/api/members/workspace`)).json()).teams.find(team => team.id === teamId)
  const before = await read()
  await page.goto(`${baseURL}/dashboard/teams/${teamId}`)
  await page.getByRole('button', { name: 'Edit team', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const textbox = label => dialog.getByRole('textbox', { name: label, exact: true })
  const toolbar = dialog.getByRole('group', { name: 'Text formatting' })
  assert.equal(await textbox('Description').innerText(), before.description)
  assert.equal(await dialog.locator('[contenteditable="true"]').count(), 1)
  await textbox('Description').fill('Team documentation')
  await toolbar.getByLabel('Text style').selectOption('2')
  await textbox('Description').press('End')
  await textbox('Description').press('Enter')
  const longText = 'Our team documents designs, decisions and lessons for future members. '.repeat(100)
  await page.keyboard.insertText(longText)
  await textbox('Description').press('Enter')
  await toolbar.getByRole('button', { name: 'Bold', exact: true }).click()
  await page.keyboard.insertText('Clear ownership')
  await toolbar.getByRole('button', { name: 'Bold', exact: true }).click()
  await page.keyboard.insertText(' and ')
  await toolbar.getByRole('button', { name: 'Italic', exact: true }).click()
  await page.keyboard.insertText('shared learning')
  await toolbar.getByRole('button', { name: 'Italic', exact: true }).click()

  await dialog.getByRole('button', { name: 'Edit Responsibilities', exact: true }).click()
  assert.equal((await textbox('Responsibilities').innerText()).replace(/\s+/g, ' '), before.responsibilities.replace(/\s+/g, ' '))
  await textbox('Responsibilities').fill('Own integration')
  await toolbar.getByRole('button', { name: 'Bullet list', exact: true }).click()
  await textbox('Responsibilities').press('End'); await textbox('Responsibilities').press('Enter')
  await page.keyboard.insertText('Review interfaces')
  await textbox('Responsibilities').press('Shift+Enter')
  await page.keyboard.insertText('Coordinate tests')

  await dialog.getByRole('button', { name: 'Edit Workflow / process', exact: true }).click()
  await textbox('Workflow / process').fill('Plan')
  await toolbar.getByRole('button', { name: 'Numbered list', exact: true }).click()
  await textbox('Workflow / process').press('End'); await textbox('Workflow / process').press('Enter')
  await page.keyboard.insertText('Build')
  await textbox('Workflow / process').press('Enter'); await page.keyboard.insertText('Test')

  await dialog.getByRole('button', { name: 'Edit Types of projects', exact: true }).click()
  await textbox('Types of projects').fill('Team handbook')
  await textbox('Types of projects').press('Control+a')
  await toolbar.getByRole('button', { name: 'Add or edit link' }).click()
  await dialog.getByLabel('Link address').fill('javascript:alert(1)')
  await dialog.getByRole('button', { name: 'Apply link', exact: true }).click()
  await dialog.getByRole('alert').filter({ hasText: 'Use a complete' }).waitFor()
  await dialog.getByLabel('Link address').fill('https://example.com/team-handbook')
  await dialog.getByRole('button', { name: 'Apply link', exact: true }).click()
  await dialog.getByRole('button', { name: 'Edit How we work', exact: true }).click()
  assert.equal(await textbox('How we work').innerText(), before.workingStyle)
  await dialog.getByRole('button', { name: 'Edit About', exact: true }).click()
  assert.ok((await textbox('Description').innerText()).includes('shared learning'))
  assert.equal(await textbox('Description').locator('h2').innerText(), 'Team documentation')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await dialog.getByRole('button', { name: 'Keep writing', exact: true }).click()
  assert.ok((await textbox('Description').innerText()).includes(longText.trim()))

  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 950 })
    assert.equal(await dialog.evaluate(node => node.scrollWidth > node.clientWidth), false, `Editor overflow at ${width}`)
    if (screenshotDir) await dialog.screenshot({ path: `${screenshotDir}/team-editor-${width}.png` })
  }
  await page.route('**/api/members/teams/' + teamId, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Test save unavailable.' }) }))
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  await dialog.getByRole('alert').filter({ hasText: 'Test save unavailable.' }).waitFor()
  assert.ok((await textbox('Description').innerText()).includes(longText.trim()))
  await page.unroute('**/api/members/teams/' + teamId)
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.reload()
  const view = page.locator('.m-team-document')
  await view.getByRole('heading', { name: 'Team documentation', exact: true }).waitFor()
  assert.equal(await view.locator('strong').innerText(), 'Clear ownership')
  assert.equal(await view.locator('em').innerText(), 'shared learning')
  assert.equal(await view.locator('ul > li').count(), 2)
  assert.equal(await view.locator('ol > li').count(), 3)
  assert.ok(await view.locator('ul br').count())
  assert.equal(await view.getByRole('link', { name: 'Team handbook' }).getAttribute('href'), 'https://example.com/team-handbook')
  assert.equal(await view.locator('[contenteditable],textarea').count(), 0)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  if (screenshotDir) await page.screenshot({ path: `${screenshotDir}/team-document-mobile.png`, fullPage: true })
  const saved = await read()
  assert.equal(saved.information.version, 1)
  assert.ok(saved.description.length > 5000)
  assert.equal(saved.workingStyle, before.workingStyle, 'Unedited legacy text is preserved')
  await page.getByRole('button', { name: 'Edit team', exact: true }).click()
  assert.equal(await textbox('Description').locator('h2').innerText(), 'Team documentation')
  await dialog.getByRole('button', { name: 'Edit Responsibilities', exact: true }).click()
  assert.equal(await textbox('Responsibilities').locator('ul > li').count(), 2)
  await textbox('Responsibilities').fill('Discard this change')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await dialog.getByRole('button', { name: 'Discard changes', exact: true }).click()
  assert.deepEqual((await read()).information, saved.information)
  for (const content of [
    { type: 'paragraph', content: [{ type: 'text', text: 'unsafe', marks: [{ type: 'link', attrs: { href: 'javascript:alert(1)' } }] }] },
    { type: 'script', text: 'alert(1)' },
    { type: 'bulletList', content: [{ type: 'text', text: 'invalid list' }] },
  ]) {
    const invalid = structuredClone(saved)
    invalid.information.sections.description = { type: 'doc', content: [content] }
    assert.equal((await api.put(route, { headers, data: invalid })).status(), 400)
  }
  assert.deepEqual((await read()).information, saved.information, 'Rejected content leaves saved documentation intact')
  const { information, ...legacy } = saved
  assert.equal((await api.put(route, { headers, data: legacy })).status(), 200)
  assert.deepEqual((await read()).information, information, 'Unchanged legacy payload retains formatting')
  await page.setViewportSize({ width: 1440, height: 1000 })
  console.log('PASS rich team documentation: long content, headings, bold/italic, lists, line breaks, safe links, section switching, save recovery, reload, discard, mobile and legacy preservation')
}
