import assert from 'node:assert/strict'
import { request } from 'playwright'

export async function checkDeletion(page, baseURL, prefix) {
  const api = page.context().request
  const headers = { 'X-Caesar-Client': 'members' }
  const url = path => `${baseURL}/api/members${path}`
  const read = async () => (await api.get(url('/workspace'))).json()
  const create = async (entity, input) => {
    const response = await api.post(url(`/${entity}`), { headers, data: input })
    assert.equal(response.status(), 200)
    return (await response.json())[entity].at(-1)
  }
  const remove = (entity, id) => api.delete(url(`/${entity}/${id}`), { headers })
  const team = await create('teams', { name: `${prefix}-Delete-Team`, description: 'Temporary deletion check', projectId: '', status: 'Planned', members: [] })
  const parent = await create('projects', { name: `${prefix}-Delete-Project`, teamId: team.id, description: 'Parent', status: 'Planned', startDate: '2026-09-28', targetDate: '2026-10-01' })
  const child = await create('projects', { ...parent, name: `${prefix}-Delete-Child`, parentProjectId: parent.id })
  const goal = await create('goals', { title: `${prefix}-Delete-Goal`, description: 'Goal', teamId: team.id, projectId: parent.id, status: 'Planned', progress: 0, deadline: '2026-10-01' })
  const update = await create('updates', { title: `${prefix}-Delete-Update`, description: 'Update', teamId: team.id, projectId: parent.id, status: 'Planned', date: '2026-09-28', author: 'Test', tags: [] })
  const entry = await create('entries', { title: `${prefix}-Delete-Data`, description: 'Result', teamId: team.id, projectId: parent.id, date: '2026-09-28', category: 'Test', value: 1, unit: '', notes: '' })
  const guest = await request.newContext()
  try { assert.equal((await guest.delete(url(`/teams/${team.id}`), { headers })).status(), 401) } finally { await guest.dispose() }
  assert.equal((await api.delete(url(`/entries/${entry.id}`), { headers: { 'X-Caesar-Client': '' } })).status(), 403)
  assert.equal((await api.delete(url('/activity/anything'), { headers })).status(), 404)
  assert.equal((await remove('teams', team.id)).status(), 400)
  assert.equal((await remove('projects', parent.id)).status(), 400)
  const dialog = page.getByRole('dialog')
  await page.goto(`${baseURL}/dashboard/projects/${parent.id}`)
  await page.getByRole('button', { name: 'Edit project', exact: true }).click()
  await dialog.getByRole('button', { name: 'Delete project', exact: true }).click()
  assert.equal(await dialog.getByRole('button', { name: 'Permanently delete project' }).isDisabled(), true)
  await dialog.getByText('1 subprojects', { exact: true }).waitFor()
  await dialog.getByRole('button', { name: 'Keep project', exact: true }).click()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()

  async function confirmDelete(label) {
    await dialog.getByRole('button', { name: `Delete ${label}`, exact: true }).click()
    await dialog.getByRole('button', { name: `Permanently delete ${label}`, exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
  }
  await page.goto(`${baseURL}/dashboard/goals`)
  await page.locator('.m-goal-card').filter({ hasText: goal.title }).getByRole('button', { name: 'Edit goal' }).click()
  await dialog.getByRole('button', { name: 'Delete goal', exact: true }).click()
  await dialog.getByRole('button', { name: 'Keep goal', exact: true }).click()
  assert.ok((await read()).goals.some(row => row.id === goal.id))
  await confirmDelete('goal')
  await page.goto(`${baseURL}/dashboard/projects/${parent.id}`)
  await page.locator('.m-update').filter({ hasText: update.title }).getByRole('button', { name: 'Edit update' }).click()
  await confirmDelete('update')
  await page.goto(`${baseURL}/dashboard/data`)
  await page.getByRole('button', { name: `Edit ${entry.title}`, exact: true }).click()
  await page.route('**/api/members/entries/' + entry.id, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Test delete unavailable.' }) }))
  await dialog.getByRole('button', { name: 'Delete data entry', exact: true }).click()
  await dialog.getByRole('button', { name: 'Permanently delete data entry', exact: true }).click()
  await dialog.getByRole('alert').filter({ hasText: 'Test delete unavailable.' }).waitFor()
  assert.ok((await read()).entries.some(row => row.id === entry.id))
  await page.unroute('**/api/members/entries/' + entry.id)
  await dialog.getByRole('button', { name: 'Permanently delete data entry', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal((await remove('entries', entry.id)).status(), 400)
  assert.equal((await api.put(url(`/entries/${entry.id}`), { headers, data: entry })).status(), 400, 'Stale edit cannot recreate a deleted item')
  await page.goto(`${baseURL}/dashboard/projects/${child.id}`)
  await page.getByRole('button', { name: 'Edit project', exact: true }).click()
  await confirmDelete('project')
  await page.waitForURL(`${baseURL}/dashboard/projects`)
  await page.goto(`${baseURL}/dashboard/projects/${parent.id}`)
  await page.getByRole('button', { name: 'Edit project', exact: true }).click()
  await dialog.getByRole('button', { name: 'Delete project', exact: true }).click()
  const raced = await create('goals', { ...goal, title: `${prefix}-Delete-Racing-Goal` })
  await dialog.getByRole('button', { name: 'Permanently delete project', exact: true }).click()
  await dialog.getByRole('alert').filter({ hasText: 'Remove or reassign' }).waitFor()
  assert.equal((await remove('goals', raced.id)).status(), 200)
  await dialog.getByRole('button', { name: 'Permanently delete project', exact: true }).click()
  await page.waitForURL(`${baseURL}/dashboard/projects`)
  await page.goto(`${baseURL}/dashboard/teams/${team.id}`)
  await page.getByRole('button', { name: 'Edit team', exact: true }).click()
  await page.setViewportSize({ width: 320, height: 950 })
  await dialog.getByRole('button', { name: 'Delete team', exact: true }).click()
  assert.equal(await dialog.evaluate(node => node.scrollWidth > node.clientWidth), false)
  await dialog.getByRole('button', { name: 'Permanently delete team', exact: true }).click()
  await page.waitForURL(`${baseURL}/dashboard/teams`)
  await page.reload()
  const final = await read()
  for (const [entity, record] of [['teams', team], ['projects', parent], ['projects', child], ['goals', goal], ['updates', update], ['entries', entry]]) {
    assert.ok(!final[entity].some(row => row.id === record.id))
    assert.equal(final.activity.filter(row => row.entityId === record.id && row.message.includes(' deleted ')).length, 1)
  }
  await page.goto(`${baseURL}/dashboard/activity`)
  await page.getByRole('heading', { name: 'Activity', exact: true }).waitFor()
  assert.equal(await page.locator('.m-activity-list li').filter({ hasText: `deleted a team: ${team.name}` }).getByRole('link').count(), 0)
  await page.setViewportSize({ width: 1440, height: 1000 })
  console.log('PASS deletion of all record types, confirmation/cancel, linked-record protection, stale changes, permissions, retry, persistence, audit history and mobile layout')
}
