import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'

const base = (process.env.CHECK_URL || 'http://localhost:5173/').replace(/\/?$/, '/')
const browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || undefined, headless: true })
const errors = []
await mkdir('artifacts', { recursive: true })
try {
  for (const [width, height] of [[1440, 1000], [1024, 768], [768, 1024], [390, 844], [320, 740], [844, 390]]) {
    const page = await browser.newPage({ viewport: { width, height }, reducedMotion: 'reduce' })
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(`${base}propulsion/`, { waitUntil: 'networkidle' })
    assert.equal(await page.title(), 'Propulsion · Phobos | CAESAR')
    assert.equal(await page.locator('h1').innerText(), 'Powering\nPhobos.')
    assert.equal(await page.locator('.propulsion-page > section').count(), 13)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Page overflow at ${width}`)
    const missingAnchors = await page.locator('a[href^="#"]').evaluateAll(links => links.filter(link => !document.getElementById(link.hash.slice(1))).map(link => link.hash))
    assert.deepEqual(missingAnchors, [])
    for (const figure of await page.locator('.propulsion-page figure').all()) {
      const box = await figure.boundingBox()
      assert.ok(box.x >= 0 && box.x + box.width <= width, `Clipped diagram at ${width}px`)
    }
    assert.equal(await page.locator('.propulsion-project-figure img').count(), 0, 'Missing original figures should not create placeholder images')
    const notes = page.locator('.propulsion-calculations')
    await notes.locator('summary').focus()
    await page.keyboard.press('Enter')
    assert.equal(await notes.getAttribute('open'), '')
    assert.match(await notes.innerText(), /0\.424 kg\/s/)
    assert.match(await notes.innerText(), /not a net upward acceleration of 5 g/)
    await page.keyboard.press('Enter')
    await page.screenshot({ path: `artifacts/propulsion-page-${width}.png`, fullPage: true })
    if (width === 1440 || width === 390) {
      await page.locator('.propulsion-hero').screenshot({ path: `artifacts/propulsion-page-hero-${width}.png` })
    }
    await page.evaluate(() => { window.__propulsionMarker = true })
    await page.locator('.propulsion-closing').getByRole('link', { name: 'Explore Electronics', exact: true }).click()
    await page.waitForURL(`${base}electronics`)
    assert.equal(await page.evaluate(() => window.__propulsionMarker), true)
    if (width <= 900) await page.locator('.menu-toggle').click()
    await page.locator('.project-toggle').focus()
    await page.keyboard.press('ArrowDown')
    await page.locator('.project-destinations').getByRole('link', { name: 'Propulsion', exact: true }).click()
    await page.waitForURL(`${base}propulsion`)
    assert.equal(await page.evaluate(() => window.__propulsionMarker), true)
    assert.equal(await page.locator('.project-destinations [aria-current="page"]').innerText(), 'Propulsion')
    assert.equal(await page.locator('.home-destinations [aria-current]').count(), 0)
    await page.reload({ waitUntil: 'networkidle' })
    assert.equal(await page.title(), 'Propulsion · Phobos | CAESAR')
    await page.locator('.propulsion-closing').getByRole('link', { name: 'Back to Phobos', exact: true }).click()
    await page.waitForURL(`${base}#projekt`)
    await page.waitForFunction(() => Math.abs(document.getElementById('projekt').getBoundingClientRect().top) < 200)
    await page.getByRole('link', { name: 'Explore Propulsion', exact: true }).click()
    await page.waitForURL(`${base}propulsion`)
    await page.goBack()
    await page.locator('.rocket-experience').waitFor()
    await page.goForward()
    await page.locator('.propulsion-page').waitFor()
    console.log(`PASS ${width} × ${height}: content, diagrams, calculations, routing, history, metadata, refresh and layout`)
    await page.close()
  }
  for (const [width, height] of [[1440, 1000], [1024, 768], [390, 844], [320, 740]]) {
    const page = await browser.newPage({ viewport: { width, height } })
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(base, { waitUntil: 'networkidle' })
    const cta = page.locator('.propulsion-cta')
    assert.equal(await cta.getAttribute('tabindex'), '-1')
    await page.getByRole('button', { name: 'Visa PROPULSION', exact: true }).click()
    await page.waitForTimeout(1500)
    assert.equal(await cta.getAttribute('tabindex'), '0')
    const bounds = await cta.boundingBox()
    assert.ok(bounds.y >= 75 && bounds.y + bounds.height < height - 60, `CTA clipped at ${width}px`)
    if (width <= 900) {
      const copy = await page.locator('.callout-propulsion').boundingBox()
      const drawing = await page.locator('.hybrid-drawing').boundingBox()
      assert.ok(drawing.y + drawing.height < copy.y, `Engine schematic overlaps copy at ${width}px: ${drawing.y + drawing.height} / ${copy.y}`)
    }
    await page.screenshot({ path: `artifacts/propulsion-cta-${width}.png` })
    await cta.click()
    await page.locator('.propulsion-page').waitFor()
    await page.waitForFunction(() => scrollY === 0)
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.propulsion-engine-plate .hybrid-flow-pulse')).animationPlayState === 'running')
    await page.locator('.propulsion-closing').scrollIntoViewIfNeeded()
    await page.waitForTimeout(1000)
    assert.equal(await page.locator('.propulsion-closing [data-reveal]').evaluate(el => getComputedStyle(el).opacity), '1')
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.propulsion-engine-plate .hybrid-flow-pulse')).animationPlayState === 'paused')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.waitForFunction(() => document.querySelectorAll('.reveal-pending').length === 0)
    assert.equal(await page.locator('.propulsion-page').evaluate(el => el.getAnimations({ subtree: true }).length), 0)
    console.log(`PASS ${width}px: animated homepage CTA, engine flow visibility, reveals and reduced motion`)
    await page.close()
  }
  assert.deepEqual(errors, [], 'Browser runtime errors')
} finally { await browser.close() }
